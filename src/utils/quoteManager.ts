// Route save-quote calls through the Shopify App Proxy so the browser never
// makes direct Supabase DNS requests (avoids ERR_NAME_NOT_RESOLVED / CORS).
const SAVE_QUOTE_URL = '/apps/shade_space/save-quote';

export interface SavedQuote {
  id: string;
  reference: string;
  expiresAt: string;
  pricingLockedUntil: string;
  quoteName: string;
  customerReference?: string | null;
  nameAutoGenerated: boolean;
  accessToken: string;
  shopifyCustomerCreated?: boolean;
  shopifyCustomerId?: string | null;
  currentStep?: number;
  totalSteps?: number;
  status?: string;
}

