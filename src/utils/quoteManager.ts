  calculations_data: ShadeCalculations;
  pricing_snapshot?: Record<string, unknown> | null;
  locked_total?: number | null;
  locked_total_currency?: string | null;
  locked_total_base_nzd?: number | null;
  locked_fx_rate?: number | null;
